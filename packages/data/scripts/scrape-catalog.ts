#!/usr/bin/env tsx
// Pull the live Shopify catalog from gentrystein.com (the store behind
// yoyochampion.com) and write packages/data/src/generated/catalog.generated.ts.
//
// Usage: pnpm --filter @yoyo/data scrape:catalog
// Output is committed; rerun when products, prices or colourways change.

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseSpecs } from '../src/store/specs';

const STORE_ORIGIN = 'https://gentrystein.com';

interface ShopifyImage { id: number; src: string; alt?: string | null; variant_ids?: number[] }
interface ShopifyVariant {
  id: number; title: string; price: string; compare_at_price: string | null;
  available: boolean; featured_image?: { src: string } | null;
}
interface ShopifyProduct {
  id: number; handle: string; title: string; body_html: string; product_type: string;
  tags: string[]; images: ShopifyImage[]; variants: ShopifyVariant[];
  options: { name: string; values: string[] }[];
}

function htmlToText(html: string): string {
  return html
    .replace(/<br\s*\/?>|<\/p>|<\/li>|<\/h\d>|<\/div>/gi, '\n')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#39;|&rsquo;|&lsquo;/g, "'")
    .replace(/&[a-z]+;|&#\d+;/gi, '')
    .replace(/[ \t]+/g, ' ')
    .replace(/\n\s*\n+/g, '\n')
    .trim();
}

async function fetchAll(): Promise<ShopifyProduct[]> {
  const res = await fetch(`${STORE_ORIGIN}/products.json?limit=250`, {
    headers: { 'User-Agent': 'yoyochampion-catalog-sync' },
  });
  if (!res.ok) throw new Error(`products.json: HTTP ${res.status}`);
  const data = (await res.json()) as { products: ShopifyProduct[] };
  return data.products;
}

async function main() {
  const products = await fetchAll();
  const entries = products.map((p) => {
    const text = htmlToText(p.body_html ?? '');
    return {
      id: String(p.id),
      handle: p.handle,
      title: p.title.trim(),
      description: text,
      specs: parseSpecs(text),
      priceFrom: Math.min(...p.variants.map((v) => Number(v.price))),
      compareAtFrom: p.variants.some((v) => v.compare_at_price)
        ? Math.min(...p.variants.filter((v) => v.compare_at_price).map((v) => Number(v.compare_at_price)))
        : undefined,
      available: p.variants.some((v) => v.available),
      optionName: p.options[0]?.name === 'Title' ? undefined : p.options[0]?.name,
      images: p.images.map((i) => i.src),
      variants: p.variants.map((v) => ({
        id: String(v.id),
        title: v.title,
        price: Number(v.price),
        compareAtPrice: v.compare_at_price ? Number(v.compare_at_price) : undefined,
        available: v.available,
        image: v.featured_image?.src ?? undefined,
      })),
    };
  });

  const __dirname = dirname(fileURLToPath(import.meta.url));
  const outPath = join(__dirname, '..', 'src', 'generated', 'catalog.generated.ts');
  mkdirSync(dirname(outPath), { recursive: true });

  const file = `// AUTO-GENERATED by packages/data/scripts/scrape-catalog.ts from ${STORE_ORIGIN}/products.json.
// Do not edit by hand. Run \`pnpm --filter @yoyo/data scrape:catalog\` to refresh.
import type { RawCatalogProduct } from '../store/catalog-types';

export const STORE_ORIGIN = ${JSON.stringify(STORE_ORIGIN)};
export const CATALOG_SYNCED_AT = ${JSON.stringify(new Date().toISOString())};

export const RAW_CATALOG: RawCatalogProduct[] = ${JSON.stringify(entries, null, 2)};
`;
  writeFileSync(outPath, file);
  console.log(`Wrote ${entries.length} products to ${outPath}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
